import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const candidatePath = path.resolve(process.argv[2]);
const digest = (bytes) => crypto.createHash("sha256").update(bytes).digest("hex");
const integrity = (bytes) => `sha512-${crypto.createHash("sha512").update(bytes).digest("base64")}`;
const metadataResponse = await fetch("https://registry.npmjs.org/@npmmo%2froster/0.0.1", { redirect: "error", signal: AbortSignal.timeout(60_000) });
assert.equal(metadataResponse.status, 200);
const metadata = await metadataResponse.json();
assert.equal(metadata.name, "@npmmo/roster");
assert.equal(metadata.version, "0.0.1");
const url = new URL(metadata.dist.tarball);
assert.equal(url.protocol, "https:");
assert.equal(url.hostname, "registry.npmjs.org");
const download = await fetch(url, { redirect: "error", signal: AbortSignal.timeout(60_000) });
assert.equal(download.status, 200);
const baseline = Buffer.from(await download.arrayBuffer());
assert.equal(digest(baseline), "e6e854508e71e3eef4a17ef88e8a019790735f65ed238e7b726c5e0434bf1fb0");
assert.equal(integrity(baseline), metadata.dist.integrity);
const candidate = fs.readFileSync(candidatePath);
const read = (archive, file) => execFileSync("tar", ["-xzOf", "-", `package/${file}`], { input: archive });
const listing = (archive) => execFileSync("tar", ["-tzf", "-"], { input: archive, encoding: "utf8" }).trim().split(/\r?\n/).sort();
assert.deepEqual(listing(candidate), listing(baseline));
assert.equal(listing(candidate).length, 5);
const unchanged = {};
for (const file of ["bundle/bin.js", "bundle/index.js", "LICENSE"]) {
  assert.deepEqual(read(candidate, file), read(baseline, file), `${file} changed`);
  unchanged[file] = digest(read(candidate, file));
}
const before = JSON.parse(read(baseline, "package.json"));
const after = JSON.parse(read(candidate, "package.json"));
assert.equal(before.version, "0.0.1");
assert.equal(after.version, "0.0.2");
delete before.version;
delete after.version;
assert.deepEqual(after, before, "manifest differs by more than version");
const readme = read(candidate, "README.md").toString();
const normalized = readme.replaceAll("https://github.com/ManagementMO/roster/blob/main/", "").replaceAll("https://github.com/ManagementMO/roster/tree/main/docs", "docs/");
assert.equal(normalized, read(baseline, "README.md").toString(), "README differs by more than absolute repository links");
const links = [...readme.matchAll(/\]\(([^)\s]+)\)/g)].map((match) => match[1]);
assert(links.length > 0);
assert(links.every((href) => /^(?:https?:\/\/|mailto:|#)/i.test(href)));
const report = { version: "0.0.2", sourceSha: process.env.APP_SHA, node: process.version, sha256: digest(candidate), integrity: integrity(candidate), baselineSha256: digest(baseline), unchanged, manifestChange: "version only", readmeChange: "absolute repository links only", links: links.length, checkedAt: new Date().toISOString() };
fs.writeFileSync(path.join(path.dirname(candidatePath), "comparison.json"), JSON.stringify(report, null, 2));
if (process.env.GITHUB_OUTPUT) fs.appendFileSync(process.env.GITHUB_OUTPUT, `sha256=${report.sha256}\n`);
console.log(JSON.stringify(report, null, 2));
